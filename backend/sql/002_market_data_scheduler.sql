-- Run once in the Supabase Dashboard SQL Editor to enable scheduled price storage.
create table if not exists public.market_data_bars (
    id bigint generated by default as identity primary key,
    symbol text not null,
    interval text not null,
    timestamp timestamptz not null,
    open double precision not null,
    high double precision not null,
    low double precision not null,
    close double precision not null,
    volume bigint not null check (volume >= 0),
    features jsonb not null default '{}'::jsonb,
    source text not null,
    retrieved_at timestamptz not null,
    unique (symbol, interval, timestamp)
);

create index if not exists market_data_bars_symbol_time_idx
    on public.market_data_bars (symbol, interval, timestamp desc);

create table if not exists public.background_job_runs (
    id bigint generated by default as identity primary key,
    job_name text not null,
    started_at timestamptz not null,
    completed_at timestamptz not null,
    status text not null check (status in ('succeeded', 'partial', 'failed')),
    rows_processed integer not null check (rows_processed >= 0),
    details jsonb not null default '{}'::jsonb
);

create index if not exists background_job_runs_name_time_idx
    on public.background_job_runs (job_name, completed_at desc);

alter table public.market_data_bars enable row level security;
alter table public.background_job_runs enable row level security;
revoke all on public.market_data_bars, public.background_job_runs from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update on public.market_data_bars, public.background_job_runs to service_role;
grant usage, select on all sequences in schema public to service_role;
